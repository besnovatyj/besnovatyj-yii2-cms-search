declare(strict_types=1);

namespace Besnovatyj\Search\contracts;

/**
 * Ядро умеет стереть свой индекс целиком и сказать, сколько места он занимает.
 *
 * Нужен очистке поискового индекса ({@see \Besnovatyj\Search\services\IndexPurger}): каталог
 * документов фасад чистит сам, а основной объём лежит в хранилище ядра (таблицы TNTSearch в базе
 * проекта, таблица в демоне Manticore), о котором фасад ничего не знает и знать не должен.
 *
 * Отдельный необязательный контракт, а не новые методы {@see SearchEngineInterface}: ядро, которое
 * его ещё не реализует, продолжает работать, просто его данные очистка не затронет. Расширение
 * основного контракта сломало бы все существующие ядра разом.
 */
interface PurgeableEngine
{
    /**
     * Стереть все данные ядра: рабочий индекс, недособранные слоты, служебные таблицы.
     *
     * После вызова ядро находится в состоянии «индекс ещё ни разу не собирали» — то же, что сразу
     * после установки, — и следующая пересборка создаёт всё заново. Стирание отсутствующего —
     * не ошибка.
     */
    public function purge(): void;

    /**
     * Сколько места занимают данные ядра, в байтах; null — посчитать нельзя.
     *
     * Значение справочное, для строки в менеджере очистки: точности до байта никто не ждёт.
     */
    public function storageBytes(): ?int;
}

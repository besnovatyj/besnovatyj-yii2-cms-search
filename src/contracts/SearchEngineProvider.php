declare(strict_types=1);

namespace Besnovatyj\Search\contracts;

/**
 * Модуль-ядро объявляет фасаду поиска, какой движок он приносит.
 *
 * Реализуется классом Yii-модуля пакета-ядра (`SearchTnt`, `SearchManticore`). Фасад находит
 * провайдеров тем же способом, что и поставщиков контента ({@see \Besnovatyj\Contracts\search\SearchableProvider}):
 * обходом зарегистрированных модулей с проверкой `instanceof` — и получает список доступных ядер,
 * не зная ни одного из них поимённо.
 *
 * Отсюда следует главное свойство: выключенный в менеджере модулей ядро-модуль в конфиг приложения
 * не попадает, значит исчезает и из списка ядер — без карт адаптеров, проверок `class_exists()` и
 * флагов «установлено». «Ядро есть в системе» и «модуль ядра включён» — одно и то же утверждение,
 * и проверяется оно в одном месте.
 *
 * Почему контракт живёт в фасаде, а не в нейтральном пакете контрактов: ядро зависит от фасада по
 * определению — оно реализует {@see SearchEngineInterface}, объявленный здесь же. Развязывать
 * нечего, в отличие от контентных модулей, которые о поиске не знают вовсе и потому получают свой
 * контракт в общем пакете.
 */
interface SearchEngineProvider
{
    /**
     * Ядра поиска, которые приносит этот модуль.
     *
     * Обычно ровно одно; массив — чтобы пакет мог предложить несколько режимов одного движка,
     * не заводя ради этого второй модуль.
     *
     * @return SearchEngineDescriptor[]
     */
    public function searchEngines(): array;
}

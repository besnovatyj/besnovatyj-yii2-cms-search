declare(strict_types=1);

namespace Besnovatyj\Search\contracts;

/**
 * Контракт ядра поиска — сменной детали фасада.
 *
 * Реализация живёт в отдельном пакете-ядре (`yii2-cms-search-tnt`, `yii2-cms-search-manticore`),
 * который зависит от фасада, но не наоборот — поэтому фасад не знает ни одного движка поимённо,
 * а движки остаются подключаемыми плагинами. Ровно та же схема, что у {@see \Besnovatyj\Editor\contracts\EditorAdapterInterface}
 * в фасаде редактора; отличие в том, что здесь два потока — запись индекса и чтение — и разные
 * ядра умеют разное, поэтому добавлен паспорт {@see EngineCapabilities}.
 *
 * Ядро отвечает ТОЛЬКО за текст: «слова → идентификаторы документов, отсортированные по
 * релевантности». Каталог документов, ссылки, статусы, фасетные подписи, пагинация в интерфейсе
 * и вёрстка выдачи — забота фасада.
 *
 * Полная переиндексация выполняется через `beginRebuild()` → `addDocuments()` → `commitRebuild()`:
 * новый индекс собирается РЯДОМ с рабочим и подменяется в самом конце, поэтому во время
 * пересборки сайт продолжает искать по старому индексу и не отдаёт пустую выдачу.
 */
interface SearchEngineInterface
{
    /**
     * Что это ядро умеет — фасад спрашивает до отрисовки страницы выдачи.
     */
    public function capabilities(): EngineCapabilities;

    /**
     * Готово ли ядро обслуживать запросы прямо сейчас.
     *
     * Для встроенных ядер — практически всегда true; для ядра, работающего с внешним демоном, —
     * проверка соединения. Фасад вызывает метод перед запросом и при false переключается на
     * запасное ядро, а не отдаёт посетителю ошибку.
     */
    public function isAvailable(): bool;

    /**
     * Почему ядро сейчас не готово; null — готово.
     *
     * Отдельный метод, а не текст рядом с `false`, потому что причины разные по смыслу и по
     * действиям администратора: «демон не отвечает» — это чинить окружение, а «индекс ещё не
     * собран этим ядром» — нажать пересборку. Схлопнутые в один `bool`, они превращаются в
     * сообщение «не отвечает» на живом демоне, по которому невозможно понять, что делать.
     *
     * Вызывается страницей состояния индекса и консольным `status`, поэтому реализация обязана
     * быть дешёвой при повторном вызове: результат проверки кэшируется на время запроса.
     */
    public function unavailableReason(): ?string;

    /**
     * Выполнить поиск и вернуть ОДНУ страницу совпадений.
     *
     * Фильтр по типам, окно пагинации и подсчёт `total` — обязанность ядра (см. {@see SearchQuery}).
     * Ядро не бросает исключение на пустую выдачу: отсутствие совпадений — это {@see SearchResult::empty()}.
     */
    public function query(SearchQuery $query): SearchResult;

    /**
     * Подсветить совпадения запроса во фрагменте текста.
     *
     * Вызывается фасадом только при {@see EngineCapabilities::$highlight}. Реализация обязана
     * применять ту же морфологию, что и при поиске (иначе по запросу «ботинок» не подсветится
     * «ботинках»), и вернуть безопасный HTML: исходный текст экранируется, добавляются только
     * теги `<mark>`.
     */
    public function highlight(string $text, string $query): string;

    /**
     * Начать сборку нового индекса рядом с рабочим.
     *
     * Повторный вызов при незавершённой сборке отбрасывает недособранное и начинает заново —
     * так прерванный процесс (упавшая консоль, таймаут) не блокирует следующую попытку.
     */
    public function beginRebuild(): void;

    /**
     * Добавить пачку документов в собираемый индекс.
     *
     * Вызывается многократно, пачками — чтобы полная переиндексация не держала в памяти весь корпус.
     *
     * @param iterable<IndexableDocument> $documents
     */
    public function addDocuments(iterable $documents): void;

    /**
     * Атомарно заменить рабочий индекс собранным и освободить временные структуры.
     */
    public function commitRebuild(): void;

    /**
     * Отказаться от собираемого индекса, оставив рабочий нетронутым.
     *
     * Вызывается фасадом при ошибке посреди переиндексации.
     */
    public function cancelRebuild(): void;

    /**
     * Обновить (или добавить) один документ в рабочем индексе.
     *
     * Вызывается только при {@see EngineCapabilities::$incremental}; ядра без инкрементальности
     * обновляются полной пересборкой.
     */
    public function indexDocument(IndexableDocument $document): void;

    /**
     * Удалить один документ из рабочего индекса.
     *
     * Вызывается только при {@see EngineCapabilities::$incremental}. Удаление отсутствующего
     * документа — не ошибка.
     */
    public function removeDocument(int $documentId): void;
}

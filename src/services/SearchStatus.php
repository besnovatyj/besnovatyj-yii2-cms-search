declare(strict_types=1);

namespace Besnovatyj\Search\services;

/**
 * Чем закончился поиск — чтобы страница выдачи объясняла пустой экран, а не молчала.
 *
 * Три разные причины «ничего не найдено» требуют трёх разных сообщений: слишком короткий запрос
 * пользователь исправит сам, отсутствующий индекс — это работа администратора, а честное «ничего
 * не нашлось» — повод предложить другой запрос.
 */
enum SearchStatus
{
    /** Запрос выполнен (совпадения могли и не найтись). */
    case Ok;

    /** Пользователь ещё ничего не ввёл. */
    case NoQuery;

    /** Запрос короче минимально допустимой длины. */
    case TooShort;

    /** Ни одно ядро поиска не отвечает — поиск временно недоступен. */
    case EngineUnavailable;

    /** Индекс пуст: его ни разу не собирали или последняя сборка не дала документов. */
    case IndexEmpty;
}
